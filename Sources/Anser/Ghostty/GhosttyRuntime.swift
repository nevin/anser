import AppKit
import GhosttyKit
import AnserCore

/// Owns the single libghostty app instance and routes its callbacks.
final class GhosttyRuntime {
    static let shared = GhosttyRuntime()

    private(set) var app: ghostty_app_t?
    private(set) var config: ghostty_config_t?
    /// The settings Anser generated for the terminal (for tests and diagnostics).
    private(set) var configText = ""
    private var tickScheduled = false
    private(set) var theme = Theme.fallback

    /// Folder holding Ghostty's resources (terminfo, shell integration).
    var resourcesDir: String? {
        if let r = Bundle.main.resourceURL?.appendingPathComponent("ghostty"), FileManager.default.fileExists(atPath: r.path) { return r.path }
        return nil
    }

    func start() -> Bool {
        if let res = resourcesDir { setenv("GHOSTTY_RESOURCES_DIR", res, 1) }
        guard ghostty_init(UInt(CommandLine.argc), CommandLine.unsafeArgv) == GHOSTTY_SUCCESS else {
            NSLog("Anser: ghostty_init failed")
            return false
        }
        config = makeConfig()
        theme = Theme(config: config)

        var rt = ghostty_runtime_config_s()
        rt.userdata = nil
        rt.supports_selection_clipboard = false
        rt.wakeup_cb = { _ in GhosttyRuntime.shared.scheduleTick() }
        rt.action_cb = { _, target, action in GhosttyRuntime.shared.handle(action: action, target: target) }
        rt.read_clipboard_cb = { ud, location, state, mimes, count, list in
            GhosttyRuntime.readClipboard(ud, location, state, mimes, count, list)
        }
        rt.confirm_read_clipboard_cb = { ud, confirm, state, request in
            GhosttyRuntime.confirmReadClipboard(ud, confirm, state, request)
        }
        rt.write_clipboard_cb = { ud, location, content, len, confirm in
            GhosttyRuntime.writeClipboard(ud, location, content, len, confirm)
        }
        rt.close_surface_cb = { ud, processAlive in
            guard let view = TerminalSurfaceView.from(ud) else { return }
            DispatchQueue.main.async { view.pane?.surfaceRequestedClose() }
        }
        app = ghostty_app_new(&rt, config)
        guard app != nil else { NSLog("Anser: ghostty_app_new failed"); return false }
        applyColorScheme()
        watchSystemAppearance()
        return true
    }

    /// Builds the Ghostty config: the user's own Ghostty config first (so an
    /// existing theme carries over), then Anser's required settings, then
    /// any extra lines from Anser's config.
    private func makeConfig() -> ghostty_config_t? {
        guard let cfg = ghostty_config_new() else { return nil }
        ghostty_config_load_default_files(cfg)
        ghostty_config_load_recursive_files(cfg)

        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Anser")
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let file = dir.appendingPathComponent("ghostty.conf")
        var lines = [
            "# Generated by Anser on every launch. Edit ~/.config/anser/config.json instead.",
            // Anser loads Ghostty's integration itself, alongside its own hooks.
            "shell-integration = none",
            // Room on the left for command block bars (Settings can change it).
            "window-padding-x = 10",
            "confirm-close-surface = false",
            "quit-after-last-window-closed = true",
            // Programs may copy to your clipboard (OSC 52) only after you agree;
            // reading it already asks. Override in [ghostty] lines if you like.
            "clipboard-write = ask",
            "clipboard-read = ask",
        ]
        lines.append("clipboard-paste-protection = \(Services.shared.config.editor.confirmMultilinePaste)")
        // Scrollback per tab (Settings → Behavior); the biggest memory use with many tabs.
        lines.append("scrollback-limit = \(Services.shared.config.scrollbackMB * 1_000_000)")
        if Services.shared.config.copyOnSelect { lines.append("copy-on-select = clipboard") }
        lines += Services.shared.config.appearance.ghosttyLines(systemIsDark: Self.systemIsDark)
        lines += Services.shared.config.ghostty
        configText = lines.joined(separator: "\n").appending("\n")
        try? configText.write(to: file, atomically: true, encoding: .utf8)
        ghostty_config_load_file(cfg, file.path)
        ghostty_config_finalize(cfg)

        let n = ghostty_config_diagnostics_count(cfg)
        for i in 0..<n {
            let d = ghostty_config_get_diagnostic(cfg, i)
            if let m = d.message { NSLog("Anser ghostty config: \(String(cString: m))") }
        }
        return cfg
    }

    func reloadConfig() {
        guard let app, let newConfig = makeConfig() else { return }
        ghostty_app_update_config(app, newConfig)
        if let old = config { ghostty_config_free(old) }
        config = newConfig
        theme = Theme(config: newConfig)
        applyColorScheme()
        NotificationCenter.default.post(name: .anserThemeChanged, object: nil)
    }

    /// Whether macOS itself is in dark mode (ignoring Anser's own override).
    static var systemIsDark: Bool {
        UserDefaults.standard.string(forKey: "AppleInterfaceStyle") == "Dark"
    }

    /// Applies Settings → Appearance mode: the window chrome, Ghostty's color
    /// scheme, and (when the theme depends on light/dark) the terminal theme.
    func applyColorScheme() {
        let look = Services.shared.config.appearance
        switch look.mode {
        case "dark": NSApp.appearance = NSAppearance(named: .darkAqua)
        case "light": NSApp.appearance = NSAppearance(named: .aqua)
        default: NSApp.appearance = nil
        }
        guard let app else { return }
        let dark = look.mode == nil ? Self.systemIsDark : look.usesDark(systemIsDark: Self.systemIsDark)
        ghostty_app_set_color_scheme(app, dark ? GHOSTTY_COLOR_SCHEME_DARK : GHOSTTY_COLOR_SCHEME_LIGHT)
    }

    private var appearanceObserver: NSObjectProtocol?
    private var lastSystemDark: Bool?

    /// Follows macOS switching between light and dark while Anser runs.
    func watchSystemAppearance() {
        lastSystemDark = Self.systemIsDark
        appearanceObserver = DistributedNotificationCenter.default().addObserver(
            forName: Notification.Name("AppleInterfaceThemeChangedNotification"), object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.systemAppearanceChanged() }
        }
    }

    func systemAppearanceChanged() {
        let dark = Self.systemIsDark
        guard dark != lastSystemDark else { return }
        lastSystemDark = dark
        applyColorScheme()
        // The theme only changes with macOS when following the system with two themes.
        let look = Services.shared.config.appearance
        if look.mode == "system", look.themeName(systemIsDark: true) != look.themeName(systemIsDark: false) { reloadConfig() }
    }

    func scheduleTick() {
        DispatchQueue.main.async { [self] in
            guard let app else { return }
            ghostty_app_tick(app)
        }
    }

    // MARK: Actions

    private func handle(action: ghostty_action_s, target: ghostty_target_s) -> Bool {
        let view: TerminalSurfaceView? = target.tag == GHOSTTY_TARGET_SURFACE
            ? TerminalSurfaceView.from(ghostty_surface_userdata(target.target.surface)) : nil
        let pane = view?.pane

        switch action.tag {
        case GHOSTTY_ACTION_SET_TITLE, GHOSTTY_ACTION_SET_TAB_TITLE:
            if let ptr = action.action.set_title.title {
                let title = String(cString: ptr)
                // In-band events from Anser's hooks on an ssh host (not a real title).
                if title.hasPrefix("\u{E000}anser:") {
                    var fields = String(title.dropFirst("\u{E000}anser:".count)).components(separatedBy: "\u{E001}")
                    let token = fields.isEmpty ? "" : fields.removeFirst()
                    DispatchQueue.main.async { pane?.session.handleRemote(token: token, fields) }
                    return true
                }
                DispatchQueue.main.async { pane?.titleChanged(title) }
            }
            return true
        case GHOSTTY_ACTION_PWD:
            if let ptr = action.action.pwd.pwd {
                let pwd = String(cString: ptr)
                DispatchQueue.main.async { pane?.pwdChanged(pwd) }
            }
            return true
        case GHOSTTY_ACTION_MOUSE_SHAPE:
            view?.setCursorShape(action.action.mouse_shape)
            return true
        case GHOSTTY_ACTION_MOUSE_VISIBILITY:
            if action.action.mouse_visibility == GHOSTTY_MOUSE_HIDDEN { NSCursor.setHiddenUntilMouseMoves(true) }
            return true
        case GHOSTTY_ACTION_OPEN_URL:
            let u = action.action.open_url
            if let ptr = u.url {
                let s = String(data: Data(bytes: ptr, count: Int(u.len)), encoding: .utf8) ?? ""
                DispatchQueue.main.async { Self.openLink(s, from: view?.window) }
            }
            return true
        case GHOSTTY_ACTION_RING_BELL:
            NSSound.beep()
            if !NSApp.isActive { NSApp.requestUserAttention(.informationalRequest) }
            return true
        case GHOSTTY_ACTION_NEW_WINDOW:
            DispatchQueue.main.async { AppDelegate.shared.newWindow(cwd: pane?.session.cwd) }
            return true
        case GHOSTTY_ACTION_NEW_TAB:
            DispatchQueue.main.async { AppDelegate.shared.newTab(from: pane) }
            return true
        case GHOSTTY_ACTION_NEW_SPLIT:
            let dir = action.action.new_split
            DispatchQueue.main.async {
                guard let pane else { return }
                pane.windowController?.split(pane, vertical: dir == GHOSTTY_SPLIT_DIRECTION_RIGHT || dir == GHOSTTY_SPLIT_DIRECTION_LEFT)
            }
            return true
        case GHOSTTY_ACTION_GOTO_SPLIT:
            let g = action.action.goto_split
            DispatchQueue.main.async {
                guard let pane else { return }
                pane.windowController?.focusPane(relativeTo: pane, forward: g != GHOSTTY_GOTO_SPLIT_PREVIOUS && g != GHOSTTY_GOTO_SPLIT_LEFT && g != GHOSTTY_GOTO_SPLIT_UP)
            }
            return true
        case GHOSTTY_ACTION_CLOSE_TAB, GHOSTTY_ACTION_CLOSE_WINDOW:
            DispatchQueue.main.async { pane?.window?.performClose(nil) }
            return true
        case GHOSTTY_ACTION_QUIT:
            DispatchQueue.main.async { NSApp.terminate(nil) }
            return true
        case GHOSTTY_ACTION_SHOW_CHILD_EXITED:
            DispatchQueue.main.async { pane?.surfaceRequestedClose() }
            return true
        case GHOSTTY_ACTION_TOGGLE_FULLSCREEN:
            DispatchQueue.main.async { pane?.window?.toggleFullScreen(nil) }
            return true
        case GHOSTTY_ACTION_RELOAD_CONFIG:
            DispatchQueue.main.async { AppDelegate.shared.reloadConfig(nil) }
            return true
        case GHOSTTY_ACTION_OPEN_CONFIG:
            DispatchQueue.main.async { AppDelegate.shared.openConfig(nil) }
            return true
        case GHOSTTY_ACTION_START_SEARCH:
            DispatchQueue.main.async { pane?.showFind() }
            return true
        case GHOSTTY_ACTION_END_SEARCH:
            return true
        case GHOSTTY_ACTION_SEARCH_TOTAL:
            let t = Int(action.action.search_total.total)
            DispatchQueue.main.async { pane?.searchUpdated(total: t) }
            return true
        case GHOSTTY_ACTION_SEARCH_SELECTED:
            let sel = Int(action.action.search_selected.selected)
            DispatchQueue.main.async { pane?.searchUpdated(selected: sel) }
            return true
        case GHOSTTY_ACTION_CELL_SIZE:
            let s = action.action.cell_size
            view?.cellSize = CGSize(width: Double(s.width), height: Double(s.height))
            return true
        case GHOSTTY_ACTION_SCROLLBAR:
            // New output or scrolling: command blocks move with the text.
            DispatchQueue.main.async { pane?.blocksOverlay.setNeedsRefresh() }
            return false
        case GHOSTTY_ACTION_RENDER, GHOSTTY_ACTION_COLOR_CHANGE,
             GHOSTTY_ACTION_RENDERER_HEALTH, GHOSTTY_ACTION_MOUSE_OVER_LINK, GHOSTTY_ACTION_SELECTION_CHANGED,
             GHOSTTY_ACTION_COMMAND_FINISHED, GHOSTTY_ACTION_PROGRESS_REPORT, GHOSTTY_ACTION_KEY_SEQUENCE,
             GHOSTTY_ACTION_KEY_TABLE, GHOSTTY_ACTION_SIZE_LIMIT, GHOSTTY_ACTION_INITIAL_SIZE, GHOSTTY_ACTION_CONFIG_CHANGE:
            return false
        default:
            return false
        }
    }

    // MARK: Links

    /// Opens a link a program printed. Web and mail links open directly; file
    /// links follow the same rules as ⌘-click (scripts and apps are only
    /// revealed); any other scheme asks first, since it can launch an app.
    static func openLink(_ s: String, from window: NSWindow?) {
        let url: URL
        if let u = URL(string: s), let scheme = u.scheme?.lowercased(), !scheme.isEmpty, scheme != "file" {
            url = u
        } else {
            let path = URL(string: s)?.scheme?.lowercased() == "file" ? (URL(string: s)?.path ?? s) : s
            if OpenSafety.canOpenDirectly(path: path) {
                NSWorkspace.shared.open(URL(fileURLWithPath: path))
            } else {
                NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: path)])
            }
            return
        }
        if OpenSafety.quietSchemes.contains(url.scheme?.lowercased() ?? "") { NSWorkspace.shared.open(url); return }
        let a = NSAlert()
        a.messageText = "Open this link?"
        a.informativeText = "A program in the terminal printed a “\(url.scheme ?? "")” link, which opens another app:\n\n\(s.prefix(300))"
        a.addButton(withTitle: "Open")
        a.addButton(withTitle: "Cancel")
        let respond: (NSApplication.ModalResponse) -> Void = { r in if r == .alertFirstButtonReturn { NSWorkspace.shared.open(url) } }
        if let window { a.beginSheetModal(for: window, completionHandler: respond) } else { respond(a.runModal()) }
    }

    // MARK: Clipboard

    private static func pasteboard(_ loc: ghostty_clipboard_e) -> NSPasteboard? {
        loc == GHOSTTY_CLIPBOARD_STANDARD ? .general : nil
    }

    private static func data(from pb: NSPasteboard, mime: String) -> Data? {
        switch mime {
        case "text/plain", "text/plain;charset=utf-8", "UTF8_STRING", "STRING", "TEXT":
            if let s = pb.string(forType: .string) { return Data(s.utf8) }
            if let urls = pb.readObjects(forClasses: [NSURL.self]) as? [URL], !urls.isEmpty {
                return Data(urls.map { $0.isFileURL ? ShellLexer.escape($0.path) : $0.absoluteString }.joined(separator: " ").utf8)
            }
            return nil
        case "text/html": return pb.data(forType: .html)
        case "image/png": return pb.data(forType: .png)
        default: return nil
        }
    }

    private static func availableMimes(_ pb: NSPasteboard) -> [String] {
        var out: [String] = []
        if pb.availableType(from: [.string, .fileURL, .URL]) != nil { out.append("text/plain") }
        if pb.availableType(from: [.html]) != nil { out.append("text/html") }
        if pb.availableType(from: [.png]) != nil { out.append("image/png") }
        return out
    }

    static func readClipboard(_ ud: UnsafeMutableRawPointer?, _ loc: ghostty_clipboard_e, _ state: UnsafeMutableRawPointer?,
                              _ mimes: UnsafePointer<UnsafePointer<CChar>?>?, _ count: Int, _ list: Bool) -> ghostty_clipboard_read_result_e {
        guard let view = TerminalSurfaceView.from(ud), let surface = view.surface, let pb = pasteboard(loc) else {
            return GHOSTTY_CLIPBOARD_READ_UNSUPPORTED
        }
        var contents: [(String, Data)] = []
        var seen = Set<String>()
        if let mimes {
            for i in 0..<count {
                guard let p = mimes[i] else { continue }
                let m = String(cString: p)
                guard seen.insert(m).inserted, let d = data(from: pb, mime: m) else { continue }
                contents.append((m, d))
            }
        }
        let available = list ? availableMimes(pb) : []
        if contents.isEmpty && !list { return GHOSTTY_CLIPBOARD_READ_UNAVAILABLE }
        complete(surface, contents: contents, available: available, state: state)
        return GHOSTTY_CLIPBOARD_READ_STARTED
    }

    static func confirmReadClipboard(_ ud: UnsafeMutableRawPointer?, _ confirm: UnsafePointer<ghostty_clipboard_confirm_s>?,
                                     _ state: UnsafeMutableRawPointer?, _ request: ghostty_clipboard_request_e) {
        guard let view = TerminalSurfaceView.from(ud), let surface = view.surface else { return }
        guard let confirm else { ghostty_surface_deny_clipboard_request(surface, state); return }
        let c = confirm.pointee
        var reps: [(String, Data)] = []
        if let contents = c.contents {
            for i in 0..<c.contents_len {
                let item = contents[i]
                reps.append((String(cString: item.mime), item.len > 0 ? Data(bytes: item.data, count: item.len) : Data()))
            }
        }
        var avail: [String] = []
        if let a = c.available { for i in 0..<c.available_len { if let p = a[i] { avail.append(String(cString: p)) } } }
        let text = reps.first { $0.0 == "text/plain" }.flatMap { String(data: $0.1, encoding: .utf8) } ?? ""

        DispatchQueue.main.async {
            let alert = NSAlert()
            switch request {
            case GHOSTTY_CLIPBOARD_REQUEST_PASTE:
                alert.messageText = "Paste this into the terminal?"
                alert.informativeText = "It has several lines or control characters, so it may run commands as soon as it's pasted:\n\n" + String(text.prefix(1200))
            default:
                alert.messageText = "A program wants to read your clipboard"
                alert.informativeText = "Allow it to read:\n\n" + String(text.prefix(600))
            }
            alert.addButton(withTitle: request == GHOSTTY_CLIPBOARD_REQUEST_PASTE ? "Paste" : "Allow")
            alert.addButton(withTitle: "Cancel")
            let respond: (NSApplication.ModalResponse) -> Void = { r in
                if r == .alertFirstButtonReturn {
                    complete(surface, contents: reps, available: avail, state: state, confirmed: true)
                } else {
                    ghostty_surface_deny_clipboard_request(surface, state)
                }
            }
            if let w = view.window { alert.beginSheetModal(for: w, completionHandler: respond) } else { respond(alert.runModal()) }
        }
    }

    static func writeClipboard(_ ud: UnsafeMutableRawPointer?, _ loc: ghostty_clipboard_e,
                               _ content: UnsafePointer<ghostty_clipboard_content_s>?, _ len: Int, _ confirm: Bool) {
        guard let pb = pasteboard(loc), let content, len > 0 else { return }
        var text: String?
        for i in 0..<len {
            let c = content[i]
            guard let m = c.mime, String(cString: m).hasPrefix("text/plain"), let d = c.data else { continue }
            text = String(data: Data(bytes: d, count: c.len), encoding: .utf8)
        }
        guard let text else { return }
        let apply = {
            pb.clearContents()
            pb.setString(text, forType: .string)
        }
        if !confirm { apply(); return }
        // A program (OSC 52) asked to write the clipboard; ask first.
        DispatchQueue.main.async {
            let alert = NSAlert()
            alert.messageText = "A program wants to copy text to your clipboard"
            alert.informativeText = String(text.prefix(600))
            alert.addButton(withTitle: "Allow")
            alert.addButton(withTitle: "Cancel")
            if alert.runModal() == .alertFirstButtonReturn { apply() }
        }
    }

    private static func complete(_ surface: ghostty_surface_t, contents: [(String, Data)], available: [String], state: UnsafeMutableRawPointer?, confirmed: Bool = false) {
        var strings: [UnsafeMutablePointer<CChar>] = []
        var buffers: [UnsafeMutableRawPointer] = []
        defer { strings.forEach { free($0) }; buffers.forEach { $0.deallocate() } }

        var cContents: [ghostty_clipboard_content_s] = []
        for (mime, data) in contents {
            guard let m = strdup(mime) else { continue }
            strings.append(m)
            let buf = UnsafeMutableRawPointer.allocate(byteCount: max(data.count, 1), alignment: 1)
            buffers.append(buf)
            data.withUnsafeBytes { if let base = $0.baseAddress { buf.copyMemory(from: base, byteCount: $0.count) } }
            cContents.append(ghostty_clipboard_content_s(mime: m, data: buf.assumingMemoryBound(to: CChar.self), len: data.count))
        }
        var cAvail: [UnsafePointer<CChar>?] = []
        for a in available { if let s = strdup(a) { strings.append(s); cAvail.append(UnsafePointer(s)) } }

        cContents.withUnsafeBufferPointer { cb in
            cAvail.withUnsafeBufferPointer { ab in
                var done = ghostty_clipboard_complete_s(
                    contents: cb.baseAddress, contents_len: cb.count,
                    available: ab.baseAddress, available_len: ab.count,
                    confirmed: confirmed, remember: false)
                ghostty_surface_complete_clipboard_request(surface, &done, state)
            }
        }
    }
}

