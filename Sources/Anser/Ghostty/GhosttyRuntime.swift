/// Colors for Anser's own UI, read from the Ghostty theme so the command bar
/// matches the terminal.
struct Theme {
    var background: NSColor
    var foreground: NSColor
    var palette: [NSColor]

    static let fallback = Theme(
        background: NSColor(red: 0.11, green: 0.11, blue: 0.13, alpha: 1),
        foreground: NSColor(white: 0.9, alpha: 1),
        palette: [
            .black, .systemRed, .systemGreen, .systemYellow, .systemBlue, .systemPurple, .systemTeal, .white,
            .gray, .systemRed, .systemGreen, .systemYellow, .systemBlue, .systemPurple, .systemTeal, .white,
        ])

    init(background: NSColor, foreground: NSColor, palette: [NSColor]) {
        self.background = background; self.foreground = foreground; self.palette = palette
    }

    init(config: ghostty_config_t?) {
        self = .fallback
        guard let config else { return }
        func color(_ key: String) -> NSColor? {
            var c = ghostty_config_color_s()
            guard ghostty_config_get(config, &c, key, UInt(key.utf8.count)) else { return nil }
            return NSColor(srgbRed: CGFloat(c.r) / 255, green: CGFloat(c.g) / 255, blue: CGFloat(c.b) / 255, alpha: 1)
        }
        if let bg = color("background") { background = bg }
        if let fg = color("foreground") { foreground = fg }
        var pal = ghostty_config_palette_s()
        if ghostty_config_get(config, &pal, "palette", UInt("palette".utf8.count)) {
            withUnsafeBytes(of: &pal.colors) { raw in
                let colors = raw.bindMemory(to: ghostty_config_color_s.self)
                palette = (0..<16).map { i in
                    let c = colors[i]
                    return NSColor(srgbRed: CGFloat(c.r) / 255, green: CGFloat(c.g) / 255, blue: CGFloat(c.b) / 255, alpha: 1)
                }
            }
        }
    }

    var isDark: Bool {
        let c = background.usingColorSpace(.sRGB) ?? background
        return (0.299 * c.redComponent + 0.587 * c.greenComponent + 0.114 * c.blueComponent) < 0.5
    }

    /// The command bar background: a touch lighter (dark themes) or darker (light themes).
    var barBackground: NSColor { background.blended(withFraction: 0.06, of: isDark ? .white : .black) ?? background }
    var dim: NSColor { foreground.withAlphaComponent(0.45) }
    var red: NSColor { palette[1] }
    var green: NSColor { palette[2] }
    var yellow: NSColor { palette[3] }
    var blue: NSColor { palette[4] }
    var magenta: NSColor { palette[5] }
    var cyan: NSColor { palette[6] }
}
